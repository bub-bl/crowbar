namespace Crowbar.Engine.InputSystem;

/// <summary>
/// Maps the cross-platform <see cref="Key"/> enum to the Windows virtual-key
/// codes consumed by the UI layer (TextInput navigation, scroll keys, Ctrl
/// shortcuts). Keys with no VK equivalent fall back to their scancode value,
/// which the UI simply ignores.
/// </summary>
public static class KeyMapping
{
    public static int ToWindowsVk(Key key) => key switch
    {
        Key.A => 0x41,
        Key.B => 0x42,
        Key.C => 0x43,
        Key.D => 0x44,
        Key.E => 0x45,
        Key.F => 0x46,
        Key.G => 0x47,
        Key.H => 0x48,
        Key.I => 0x49,
        Key.J => 0x4A,
        Key.K => 0x4B,
        Key.L => 0x4C,
        Key.M => 0x4D,
        Key.N => 0x4E,
        Key.O => 0x4F,
        Key.P => 0x50,
        Key.Q => 0x51,
        Key.R => 0x52,
        Key.S => 0x53,
        Key.T => 0x54,
        Key.U => 0x55,
        Key.V => 0x56,
        Key.W => 0x57,
        Key.X => 0x58,
        Key.Y => 0x59,
        Key.Z => 0x5A,
        Key.D0 => 0x30,
        Key.D1 => 0x31,
        Key.D2 => 0x32,
        Key.D3 => 0x33,
        Key.D4 => 0x34,
        Key.D5 => 0x35,
        Key.D6 => 0x36,
        Key.D7 => 0x37,
        Key.D8 => 0x38,
        Key.D9 => 0x39,
        Key.Enter => 0x0D,
        Key.Escape => 0x1B,
        Key.Backspace => 0x08,
        Key.Tab => 0x09,
        Key.Space => 0x20,
        Key.Delete => 0x2E,
        Key.Insert => 0x2D,
        Key.Home => 0x24,
        Key.End => 0x23,
        Key.PageUp => 0x21,
        Key.PageDown => 0x22,
        Key.Up => 0x26,
        Key.Down => 0x28,
        Key.Left => 0x25,
        Key.Right => 0x27,
        Key.LeftShift => 0xA0,
        Key.RightShift => 0xA1,
        Key.LeftControl => 0xA2,
        Key.RightControl => 0xA3,
        Key.LeftAlt => 0x12,
        Key.RightAlt => 0x12,
        Key.F1 => 0x70, Key.F2 => 0x71, Key.F3 => 0x72, Key.F4 => 0x73,
        Key.F5 => 0x74, Key.F6 => 0x75, Key.F7 => 0x76, Key.F8 => 0x77,
        Key.F9 => 0x78, Key.F10 => 0x79, Key.F11 => 0x7A, Key.F12 => 0x7B,
        _ => (int)key
    };
}
